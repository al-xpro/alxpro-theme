import type { Hex, Palette } from "../palette.ts";
import { vscodeTheme } from "./vscode.ts";

/*
 * The npm package `alxpro-theme`, for sites and docs: the themes as Shiki
 * reads them, the terminal colors as xterm.js reads them, the whole palette,
 * and CSS custom properties. Every function returns file contents;
 * `scripts/build.ts` writes them into `npm/`.
 */

const ANSI = [
  "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
  "brightBlack", "brightRed", "brightGreen", "brightYellow",
  "brightBlue", "brightMagenta", "brightCyan", "brightWhite",
] as const;

/**
 * The VS Code theme without what only VS Code reads, named by its slug
 * (`alxpro-dark`), which is how Shiki refers to a theme.
 */
export function shikiTheme(p: Palette) {
  const { $schema: _schema, semanticHighlighting: _semantic, ...theme } = vscodeTheme(p);
  return { ...theme, name: p.slug, displayName: p.name };
}

/**
 * xterm.js's `ITheme` keys, so the colors drive a real terminal unchanged,
 * plus the chrome a terminal block draws around them: its title bar, border,
 * secondary text and prompt.
 */
export function terminalTheme(p: Palette) {
  const t = p.terminal;
  return {
    background: t.background,
    foreground: t.foreground,
    cursor: t.cursor,
    cursorAccent: t.background,
    selectionBackground: t.selection,
    selectionForeground: p.ui.strong,
    ...Object.fromEntries(ANSI.map((name, i) => [name, t.ansi[i]])),
    header: p.ui.header,
    border: p.ui.border,
    muted: p.ui.muted,
    prompt: t.ansi[8],
  } as Record<string, Hex>;
}

const BANNER = "// Generated by `npm run build` from src/palette.ts in https://github.com/al-xpro/alxpro-theme. Don't edit.";

export function indexJs(dark: Palette, light: Palette): string {
  const json = (value: unknown) => JSON.stringify(value, null, 2);
  return [
    BANNER,
    "",
    "/** AlxPro Dark as a Shiki / TextMate theme. */",
    `export const alxproDark = ${json(shikiTheme(dark))};`,
    "",
    "/** AlxPro Light as a Shiki / TextMate theme. */",
    `export const alxproLight = ${json(shikiTheme(light))};`,
    "",
    "/** Both themes, keyed the way Shiki's `themes` option takes them. */",
    "export const themes = { dark: alxproDark, light: alxproLight };",
    "",
    "/** The terminal colors, as xterm.js's `ITheme`, with a terminal block's chrome. */",
    `export const terminal = ${json({ dark: terminalTheme(dark), light: terminalTheme(light) })};`,
    "",
    "/** Every color: syntax roles, terminal and editor UI. */",
    `export const palette = ${json({ dark, light })};`,
    "",
  ].join("\n");
}

export function indexDts(dark: Palette): string {
  const id = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
  const keys = (o: object, indent: string) => Object.keys(o).map((k) => `${indent}${id(k)}: string;`).join("\n");
  return `${BANNER}

/** A TextMate theme, as Shiki, rehype-pretty-code and Expressive Code take it. */
export type TextMateTheme = {
  name: string;
  displayName: string;
  type: "dark" | "light";
  colors: Record<string, string>;
  tokenColors: { scope: string[]; settings: { foreground?: string; fontStyle?: string } }[];
};

/** xterm.js's ITheme keys, and a terminal block's chrome. */
export type TerminalTheme = {
${keys(terminalTheme(dark), "  ")}
};

export type Palette = {
  name: string;
  slug: string;
  type: "dark" | "light";
  syntax: {
${keys(dark.syntax, "    ")}
  };
  terminal: { background: string; foreground: string; cursor: string; selection: string; ansi: string[] };
  ui: {
${keys(dark.ui, "    ")}
  };
};

export declare const alxproDark: TextMateTheme;
export declare const alxproLight: TextMateTheme;
export declare const themes: { dark: TextMateTheme; light: TextMateTheme };
export declare const terminal: { dark: TerminalTheme; light: TerminalTheme };
export declare const palette: { dark: Palette; light: Palette };
`;
}

/**
 * Every color as a custom property: light on `:root`, dark under `.dark` or
 * `[data-theme="dark"]`, the way Tailwind and next-themes switch.
 * `--alxpro-syntax-keyword`, `--alxpro-terminal-red`, `--alxpro-ui-background`.
 */
export function css(dark: Palette, light: Palette): string {
  const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  const vars = (p: Palette) =>
    [
      ...Object.entries(p.syntax).map(([k, v]) => `--alxpro-syntax-${kebab(k)}: ${v};`),
      ...Object.entries(terminalTheme(p)).map(([k, v]) => `--alxpro-terminal-${kebab(k)}: ${v};`),
      ...Object.entries(p.ui).map(([k, v]) => `--alxpro-ui-${kebab(k)}: ${v};`),
    ]
      .map((line) => `  ${line}`)
      .join("\n");
  return `/* ${BANNER.slice(3)} */

:root {
${vars(light)}
}

.dark,
[data-theme="dark"] {
${vars(dark)}
}
`;
}

